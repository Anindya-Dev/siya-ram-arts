async def seed_database(force_reseed: bool = False):
    async with async_session_factory() as db:
        if not force_reseed:
            loc_res = await db.execute(select(Location))
            existing_loc = loc_res.scalars().first()
            prod_res = await db.execute(select(Product))
            existing_prods = prod_res.scalars().all()
            if existing_loc and len(existing_prods) >= 30:
                logger.info(f"Database already seeded with {len(existing_prods)} products.")
                return

        logger.info(f"Starting database seed with {len(IDOL_PRODUCTS_DATA)} handcrafted idols...")

        # 1. Locations
        loc_res = await db.execute(select(Location))
        locations = {loc.code: loc for loc in loc_res.scalars().all()}

        if "JPR" not in locations:
            jaipur = Location(
                id=str(uuid.uuid4()),
                code="JPR",
                name="Jaipur Artisan Atelier",
                address="Johari Bazaar, Pink City",
                city="Jaipur",
                state="Rajasthan",
                is_active=True,
            )
            db.add(jaipur)
            locations["JPR"] = jaipur

        if "KSH" not in locations:
            kashi = Location(
                id=str(uuid.uuid4()),
                code="KSH",
                name="Kashi Sanctum Studio",
                address="Assi Ghat Marg",
                city="Varanasi",
                state="Uttar Pradesh",
                is_active=True,
            )
            db.add(kashi)
            locations["KSH"] = kashi

        await db.flush()

        # 2. Staff and Admin Users
        user_res = await db.execute(select(User).where(User.email == "acharya@siyaramarts.com"))
        if not user_res.scalars().first():
            admin_user = User(
                id=str(uuid.uuid4()),
                clerk_user_id="user_admin_siyaram_01",
                email="acharya@siyaramarts.com",
                first_name="Acharya",
                last_name="Sharma",
                phone="+919829012345",
                role=UserRole.ADMIN,
            )
            staff_user = User(
                id=str(uuid.uuid4()),
                clerk_user_id="user_staff_siyaram_02",
                email="atelier.manager@siyaramarts.com",
                first_name="Radheshyam",
                last_name="Verma",
                phone="+919829054321",
                role=UserRole.STAFF,
            )
            db.add_all([admin_user, staff_user])
            await db.flush()

        # 3. Products
        loc_map = {"JPR": locations["JPR"].id, "KSH": locations["KSH"].id}

        for pdata in IDOL_PRODUCTS_DATA:
            existing_p = await db.execute(select(Product).where(Product.sku == pdata["sku"]))
            if existing_p.scalars().first():
                continue

            prod_data = dict(pdata)
            variants_list = [dict(v) for v in prod_data.pop("variants", [])]
            prod = Product(id=str(uuid.uuid4()), **prod_data)
            db.add(prod)
            await db.flush()

            for vdata in variants_list:
                stock_dict = vdata.pop("stock", {})
                variant = ProductVariant(
                    id=str(uuid.uuid4()),
                    product_id=prod.id,
                    **vdata,
                )
                db.add(variant)
                await db.flush()

                # Add inventory items for locations
                for loc_code, count in stock_dict.items():
                    loc_id = loc_map[loc_code]
                    inv_item = InventoryItem(
                        id=str(uuid.uuid4()),
                        variant_id=variant.id,
                        location_id=loc_id,
                        stock_count=count,
                        reserved_count=0,
                        low_stock_threshold=2,
                    )
                    db.add(inv_item)

                    ledger = StockLedgerEntry(
                        variant_id=variant.id,
                        location_id=loc_id,
                        delta=count,
                        reason=LedgerReason.RESTOCK,
                        actor="initial_seed",
                        reference_id=f"INIT-{variant.sku}",
                        note="Initial atelier stock onboarding",
                    )
                    db.add(ledger)

        await db.commit()
        logger.info(f"Successfully seeded database with all {len(IDOL_PRODUCTS_DATA)} handcrafted idols and initial stock!")


if __name__ == "__main__":
    asyncio.run(seed_database(force_reseed=True))
